class AppStrings {
  AppStrings(this.lang);
  final String lang;

  /// Dynamic live UI translation cache for any of the 90+ world languages:
  /// `_dynamicUiCache[langCode][stringKey] = translatedText`.
  static final Map<String, Map<String, String>> _dynamicUiCache = {};

  static void setDynamicTranslations(
    String langCode,
    Map<String, String> values,
  ) {
    _dynamicUiCache[langCode] = {
      ...(_dynamicUiCache[langCode] ?? const {}),
      ...values,
    };
  }

  static bool hasFullCoverage(String langCode) {
    if (langCode == 'uk' || langCode == 'en') return true;
    return missingEnglishSourceStrings(langCode).isEmpty;
  }

  /// Returns all string keys that do not yet have a built-in OR cached dynamic translation
  /// for [langCode], mapped to their English source string.
  static Map<String, String> missingEnglishSourceStrings(String langCode) {
    final res = <String, String>{};
    if (langCode == 'uk' || langCode == 'en') return res;
    final dynamicMap = _dynamicUiCache[langCode];
    for (final entry in _translations.entries) {
      final hasStatic = entry.value.containsKey(langCode);
      final hasDynamic = dynamicMap != null &&
          (dynamicMap[entry.key]?.trim().isNotEmpty ?? false);
      if (!hasStatic && !hasDynamic) {
        res[entry.key] = entry.value['en'] ?? entry.value['uk'] ?? entry.key;
      }
    }
    return res;
  }

  static Map<String, String> allEnglishSourceStrings() {
    final res = <String, String>{};
    for (final entry in _translations.entries) {
      res[entry.key] = entry.value['en'] ?? entry.value['uk'] ?? entry.key;
    }
    return res;
  }

  static AppStrings of(BuildContext context) {
    final code = AppScope.of(context).settings.nativeLanguageCode;
    return AppStrings(code);
  }

  /// Returns the localized name of a [LanguageOption] in the current UI language.
  String langName(LanguageOption option) {
    if (lang == 'uk') return '${option.nameUk} (${option.displayNativeName})';
    if (option.code == lang) return option.displayNativeName;
    if (option.nativeName.isNotEmpty &&
        option.nativeName != option.englishName) {
      return '${option.displayNativeName} • ${option.englishName}';
    }
    return option.englishName;
  }

  /// Concise localized language name suitable for inline badges and warnings.
  String shortLangName(LanguageOption option) {
    if (lang == 'uk') return option.nameUk;
    if (option.code == lang) return option.displayNativeName;
    return option.englishName;
  }

